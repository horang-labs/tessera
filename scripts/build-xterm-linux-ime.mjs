// Rebuild only the Linux browser bundle. The installed npm package stays stock.
import { cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const packageDir = path.join(root, 'node_modules/@xterm/xterm');
const { version } = JSON.parse(await readFile(path.join(packageDir, 'package.json'), 'utf8'));
if (version !== '6.1.0-beta.289') throw new Error(`Expected xterm beta.289, got ${version}`);
const temp = await mkdtemp(path.join(tmpdir(), 'tessera-xterm-linux-'));

async function replaceOnce(file, before, after) {
  const target = path.join(temp, 'src', file);
  const source = await readFile(target, 'utf8');
  if (source.split(before).length !== 2) throw new Error(`Unexpected xterm source: ${file}`);
  await writeFile(target, source.replace(before, after));
}

try {
  await cp(path.join(packageDir, 'src'), path.join(temp, 'src'), { recursive: true });
  const patch = path.join(root, 'patches/xterm-6.1.0-beta.289-linux-ime.patch');
  execFileSync('git', ['apply', '--check', '--unsafe-paths', `--directory=${temp}`, patch]);
  execFileSync('git', ['apply', '--unsafe-paths', `--directory=${temp}`, patch]);

  // Same safeguards as patch-xterm-touch-scroll/mouse-report-coords, at source level.
  await replaceOnce('browser/services/MouseService.ts',
    '    if (!this._bufferService.buffer.hasScrollback) {\n      this._handleTouchScrollAsKeys(e);\n      return;\n    }',
    '    // Tessera: do not turn touch scrolling into PTY arrow-key input.');
  await replaceOnce('browser/services/MouseCoordsService.ts',
    '    if (!this._charSizeService.hasValidSize) {',
    '    if (!this._charSizeService.hasValidSize || !Number.isFinite(coords[0]) || !Number.isFinite(coords[1])) {');

  const xtermLicense = await readFile(path.join(packageDir, 'LICENSE'), 'utf8');
  const patchReadme = await readFile(path.join(root, 'patches/README.md'), 'utf8');
  const orcaLicense = patchReadme.slice(patchReadme.indexOf('Copyright (c) 2026 Lovecast Inc.'));
  const result = await build({
    entryPoints: [path.join(temp, 'src/browser/public/Terminal.ts')],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    write: false,
    legalComments: 'inline',
    tsconfigRaw: { compilerOptions: { experimentalDecorators: true, useDefineForClassFields: false } },
    banner: { js: `/* eslint-disable */\n// Generated by npm run vendor:xterm-linux-ime. xterm 6.1.0-beta.289, Linux IME backport.\n/*!\n${xtermLicense}\n${orcaLicense}\n*/` },
  });
  await writeFile(path.join(root, 'src/lib/terminal/vendor/xterm-linux-ime.mjs'), result.outputFiles[0].contents);
  console.log('Built Linux-only xterm beta.289 IME bundle.');
} finally {
  await rm(temp, { recursive: true, force: true });
}
